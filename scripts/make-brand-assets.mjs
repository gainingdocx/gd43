// Generates all brand assets from the master logo PNG.
// Usage: node scripts/make-brand-assets.mjs [path-to-master-logo.png]
//
// Outputs:
//   app/icon.png        256px, circular-masked (browser favicon via App Router)
//   app/apple-icon.png  180px, white square (iOS home screen)
//   public/logo.png     512px (site headers, og fallback)
//   lib/brand/logo-data.ts  base64 of a 220px copy (embedded into PDFs —
//                           Workers have no fs, so the bytes ship in-bundle)

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = process.argv[2] ?? "C:/Users/dell/Downloads/GainingDocx_logo.png";

const circleMask = (size) =>
  Buffer.from(
    `<svg width="${size}" height="${size}"><circle cx="${size / 2}" cy="${size / 2}" r="${size / 2}" fill="#fff"/></svg>`
  );

async function make() {
  // Favicon: circular mask so the white square vanishes in browser tabs.
  const icon = await sharp(SRC)
    .resize(256, 256)
    .composite([{ input: circleMask(256), blend: "dest-in" }])
    .png({ palette: true, quality: 90 })
    .toBuffer();
  writeFileSync(join(ROOT, "app", "icon.png"), icon);

  // Apple touch icon: iOS rounds corners itself; keep the white square.
  const apple = await sharp(SRC)
    .resize(180, 180)
    .png({ palette: true, quality: 90 })
    .toBuffer();
  writeFileSync(join(ROOT, "app", "apple-icon.png"), apple);

  // Header/site logo.
  const site = await sharp(SRC)
    .resize(512, 512)
    .png({ palette: true, quality: 90 })
    .toBuffer();
  writeFileSync(join(ROOT, "public", "logo.png"), site);

  // PDF-embedded copy, kept small (bundle bytes).
  const pdfCopy = await sharp(SRC)
    .resize(220, 220)
    .png({ palette: true, quality: 80 })
    .toBuffer();
  mkdirSync(join(ROOT, "lib", "brand"), { recursive: true });
  writeFileSync(
    join(ROOT, "lib", "brand", "logo-data.ts"),
    `// Generated by scripts/make-brand-assets.mjs — do not edit by hand.\n` +
      `// 220px PNG of the GainingDocx logo, embedded into PDF exports\n` +
      `// (Workers cannot read files at runtime).\n` +
      `export const LOGO_PNG_BASE64 =\n  "${pdfCopy.toString("base64")}";\n`
  );

  console.log(
    `icon ${icon.length}B, apple ${apple.length}B, site ${site.length}B, pdf ${pdfCopy.length}B`
  );
}

make();
