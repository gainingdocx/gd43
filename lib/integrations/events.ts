export type IntegrationEventType = (typeof INTEGRATION_EVENTS)[number]["type"];

export const EVENT_TYPES = INTEGRATION_EVENTS.map((event) => event.type) as readonly IntegrationEventType[];

/**
 * Events that mean "something is wrong and a person should look now".
 *
 * A destination set to `critical` receives only these. Chat channels are the
 * reason this exists: a Slack channel that pings on every parsed document is
 * muted within a week, and then the critical ones are missed too.
 */
export const CRITICAL_EVENT_TYPES: readonly IntegrationEventType[] = [
  "document.failed",
  "document.review_required",
  "discrepancy.created",
  "charge.alert",
  "integration.delivery_failed",
];

export function isCriticalEvent(type: IntegrationEventType, data: Record<string, unknown>): boolean {
  // An amber discrepancy is a warning, not an incident. Filtering on the event
  // name alone would make the "critical only" setting useless for the single
  // event type customers care most about.
  if (type === "discrepancy.created") return data.severity === "red";
  return CRITICAL_EVENT_TYPES.includes(type);
}

export function eventDefinition(type: string) {
  return INTEGRATION_EVENTS.find((event) => event.type === type) ?? null;
}

export function isIntegrationEvent(value: string): value is IntegrationEventType {
  return EVENT_TYPES.includes(value as IntegrationEventType);
}
