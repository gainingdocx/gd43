// This file is the contract. The webhook signup UI, the `/v1/events` endpoint,
// the developer documentation and the delivery engine all read from here, so a
// new event type cannot ship documented-but-not-sent or sent-but-undocumented.
//
// Event names are `resource.past_tense_verb` and are permanent. Renaming one
// breaks every customer filter silently — a receiver subscribed to a name that
// no longer exists gets no error, just silence — so a superseded event is
// deprecated in place, never renamed.

